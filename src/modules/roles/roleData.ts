import { SystemRole, ModulePermission } from './roleTypes';

export const MODULE_KEYS = [
  { key: 'crm', name: 'CRM & Sales' },
  { key: 'inventory', name: 'Inventory Management' },
  { key: 'projects', name: 'Project Management' },
  { key: 'installation', name: 'Installation Management' },
  { key: 'support', name: 'Warranty & Support' },
  { key: 'finance', name: 'Finance & Analytics' },
  { key: 'users', name: 'User Management' },
  { key: 'settings', name: 'System Settings' },
];

const makePerms = (
  rules: Record<string, Partial<Record<'view' | 'create' | 'edit' | 'delete' | 'manage', boolean>>>
): ModulePermission[] => {
  return MODULE_KEYS.map((m) => {
    const r = rules[m.key] || {};
    return {
      moduleKey: m.key,
      moduleName: m.name,
      view: Boolean(r.view),
      create: Boolean(r.create),
      edit: Boolean(r.edit),
      delete: Boolean(r.delete),
      manage: Boolean(r.manage),
    };
  });
};

